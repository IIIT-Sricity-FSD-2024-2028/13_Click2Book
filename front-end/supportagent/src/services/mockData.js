/**
 * Calculates the exact financial loss and commission breakdown
 * adhering strictly to Click2Book NestJS 90/10 revenue split rules.
 */
export function calculateFinancialImpact(originalFare = 2000, category = 'CANCELLATION', customCancelFee = null) {
  const fare = Math.max(100, Number(originalFare) || 2000);
  let cancelFee = customCancelFee !== null && customCancelFee !== undefined
    ? Number(customCancelFee)
    : Math.max(100, Math.round(fare * 0.15));
  if (cancelFee > fare) cancelFee = fare;

  const customerRefund = Math.max(0, fare - cancelFee);

  // Click2Book Standard Split: 90% Provider, 10% Platform Commission
  const providerRate = 0.90;
  const platformRate = 0.10;

  const originalProviderShare = Math.round(fare * providerRate); // e.g. ₹1,800
  const originalPlatformCommission = Math.round(fare * platformRate); // e.g. ₹200

  // Cancellation charge split: 90% retained by provider, 10% by platform
  const providerCancellationShare = Math.round(cancelFee * providerRate); // e.g. ₹270
  const platformCancellationShare = cancelFee - providerCancellationShare; // e.g. ₹30

  // Estimated financial loss to the service provider:
  // Instead of receiving originalProviderShare (₹1,800), provider retains providerCancellationShare (₹270).
  // Net Loss = ₹1,800 - ₹270 = ₹1,530 (which is exactly 90% of the customer refund ₹1,700).
  const providerFinancialLoss = originalProviderShare - providerCancellationShare;
  const platformFinancialLoss = originalPlatformCommission - platformCancellationShare; // 10% of customer refund

  return {
    originalAmount: fare,
    cancellationCharges: cancelFee,
    customerRefund: customerRefund,
    providerOriginalShare: originalProviderShare,
    platformCommission: originalPlatformCommission,
    providerCancellationShare: providerCancellationShare,
    platformCancellationShare: platformCancellationShare,
    providerFinancialLoss: providerFinancialLoss,
    platformFinancialLoss: platformFinancialLoss,
    deductionsSummary: `Platform fee: ₹${originalPlatformCommission} (10%). Operator retained cancellation fee: ₹${providerCancellationShare} (90%).`,
    lossFormula: `Expected Share (₹${originalProviderShare}) − Retained Fee (₹${providerCancellationShare}) = ₹${providerFinancialLoss}`,
  };
}

